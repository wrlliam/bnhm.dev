#!/usr/bin/env node
// Encodes the contact address (from CONTACT_EMAIL) into src/lib/contact.generated.ts.
// The plaintext address must never be committed; only the encoded output is.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outFile = resolve(root, "src/lib/contact.generated.ts");
const KEY = "b4nh"; // short XOR key; obfuscation, not encryption

function readEnvFile(name) {
  const file = resolve(root, name);
  if (!existsSync(file)) return {};
  return Object.fromEntries(
    readFileSync(file, "utf8")
      .split(/\r?\n/)
      .map((l) => l.trim())
      .filter((l) => l && !l.startsWith("#") && l.includes("="))
      .map((l) => {
        const i = l.indexOf("=");
        return [
          l.slice(0, i).trim(),
          l
            .slice(i + 1)
            .trim()
            .replace(/^["']|["']$/g, ""),
        ];
      }),
  );
}

const address =
  process.env.CONTACT_EMAIL ??
  readEnvFile(".env.local").CONTACT_EMAIL ??
  readEnvFile(".env").CONTACT_EMAIL;

if (!address) {
  if (existsSync(outFile)) {
    console.log(
      "[encode-email] CONTACT_EMAIL not set; keeping existing contact.generated.ts",
    );
    process.exit(0);
  }
  console.warn("[encode-email] CONTACT_EMAIL not set; writing empty contact parts");
}

const xor = (s) =>
  Array.from(s, (c, i) =>
    String.fromCharCode(c.charCodeAt(0) ^ KEY.charCodeAt(i % KEY.length)),
  ).join("");

function encode(value) {
  if (!value) return [];
  const size = Math.ceil(value.length / 3);
  const parts = [];
  for (let i = 0; i < value.length; i += size) parts.push(value.slice(i, i + size));
  return parts
    .reverse()
    .map((p) => Buffer.from(xor([...p].reverse().join("")), "binary").toString("base64"));
}

const parts = encode(address ?? "");
const source = `// Generated by scripts/encode-email.mjs. Do not edit.
export const k = ${JSON.stringify(KEY)};
export const p: readonly string[] = ${JSON.stringify(parts)};
`;

writeFileSync(outFile, source);
console.log(`[encode-email] wrote ${parts.length} encoded parts`);
